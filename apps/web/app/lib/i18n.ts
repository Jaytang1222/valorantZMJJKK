export const messages: Record<Locale, Record<string, string>> = { zh, en };

export type MessageKey = keyof typeof zh;

export function t(locale: Locale, key: MessageKey): string {
  return messages[locale][key] ?? zh[key];
}

export function tWith(
  locale: Locale,
  key: MessageKey,
  params: Record<string, string | number>,
): string {
  return t(locale, key).replace(/\{(\w+)\}/g, (match, name) =>
    String(params[name] ?? match),
  );
}

export function detectLocale(
  stored: string | null | undefined,
  acceptLanguage: string | null | undefined,
): Locale {
  if (stored === "zh" || stored === "en") return stored;
  if (acceptLanguage?.toLowerCase().startsWith("zh")) return "zh";
  return "en";
}

export function readStoredLocale(): Locale | null {
  if (typeof window === "undefined") return null;
  const value = localStorage.getItem(LOCALE_COOKIE);
  return value === "zh" || value === "en" ? value : null;
}
